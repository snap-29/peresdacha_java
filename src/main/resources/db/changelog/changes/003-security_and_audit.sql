CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL
);
ALTER TABLE tasks ADD COLUMN owner_id BIGINT REFERENCES users(id);
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(255) NOT NULL,
    task_id BIGINT,
    created_at TIMESTAMP NOT NULL
);
-- No FK from audit_logs.task_id: the outer task transaction can roll back independently.
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    expiry_date TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_tasks_owner ON tasks(owner_id);
CREATE INDEX idx_tasks_status_priority ON tasks(status, priority);
CREATE INDEX idx_refresh_user ON refresh_tokens(user_id);

--rollback DROP TABLE refresh_tokens; DROP TABLE audit_logs; ALTER TABLE tasks DROP COLUMN owner_id; DROP TABLE users;
